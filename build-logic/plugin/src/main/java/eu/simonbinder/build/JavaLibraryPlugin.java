package eu.simonbinder.build;

import com.diffplug.gradle.spotless.SpotlessExtension;
import com.diffplug.gradle.spotless.SpotlessPlugin;
import org.gradle.api.Plugin;
import org.gradle.api.Project;
import org.gradle.api.artifacts.VersionCatalogsExtension;
import org.jspecify.annotations.NonNull;

public class JavaLibraryPlugin implements Plugin<Project> {
    @Override
    public void apply(@NonNull Project target) {
        var plugins = target.getPlugins();
        plugins.apply(JavaLibraryPlugin.class);
        plugins.apply("java-library");
        plugins.apply(SpotlessPlugin.class);

        var libs = target.getExtensions().getByType(VersionCatalogsExtension.class).named("libs");
        var googleJavaFormat = libs.findVersion("googleJavaFormat").orElseThrow().getRequiredVersion();

        target.getExtensions().configure(SpotlessExtension.class, spotless -> {
            // google-java-format indents with two spaces.
            spotless.java(java -> {
                // Only format hand-written sources, not those generated by the endive compiler.
                java.target("src/**/*.java");
                java.googleJavaFormat(googleJavaFormat);
            });
        });
    }
}
